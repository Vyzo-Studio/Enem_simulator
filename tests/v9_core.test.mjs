import {isSupportedVisual} from '../academy/v11-composer.mjs';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script,createContext} from 'node:vm';
import {sampleDiagnostic,suitableQuestions,analyzeAnswers,topicRecommendations,buildAdaptiveSchedule,verifyPlan,isGoalEvaluated} from '../academy/v9-core.mjs';
const ctx=createContext({window:{}});
for(const p of ['questions.js','extra_questions.js','advanced_questions.js'])new Script(readFileSync(new URL('../src/'+p,import.meta.url),'utf8')).runInContext(ctx);
const bank=ctx.window.QUESTION_BANK;
assert.equal(bank.length,224);
const enem={id:'a',type:'ENEM',name:'ENEM 2026',subjects:['Matemática','Natureza','Humanas','Linguagens'],priority:'high',status:'preparing'};
const contest={id:'b',type:'Concurso público',name:'Banco',subjects:['Português'],priority:'medium',status:'preparing',provisional:false};
const q=sampleDiagnostic(bank,enem,20);
assert.equal(q.length,20);assert.equal(new Set(q.map(x=>x.id)).size,20);
assert(q.every(x=>!x.visual||isSupportedVisual(x.visual)),'Gráficos válidos não podem ser excluídos do diagnóstico');
assert.equal(suitableQuestions(bank,contest).length,0,'Não inventar itens específicos de concursos');
assert(suitableQuestions(bank,{...contest,provisional:true}).length>=10);
const a={id:'d1',goalId:'a',status:'in_progress',kind:'initial',ids:q.map(x=>x.id),answers:{},startedAt:Date.now()};
assert.equal(isGoalEvaluated(enem,[a]),false);
const shallow={...a,status:'completed',report:{answered:1},ids:a.ids};assert.equal(isGoalEvaluated(enem,[shallow]),false,'Uma resposta não autoriza plano personalizado');
let t=buildAdaptiveSchedule({goals:[enem,contest],assessments:[a],availability:{0:120,1:120,2:120,3:120,4:120,5:120,6:120},bank,days:7});assert.equal(t.length,0,'Plano inicial deve ficar bloqueado');
q.forEach((item,i)=>{if(i<10)a.answers[item.id]=i%2?((item.answer+1)%5):item.answer;});
a.status='completed';a.completedAt=Date.now();a.report=analyzeAnswers(enem,a,bank);
assert.equal(a.report.correct,5);assert.equal(a.report.wrong,5);assert.equal(a.report.blank,10);assert.equal(a.report.answered,10);assert.equal(a.report.accuracy,50);assert.equal(a.report.coverage,50);
assert(Object.values(a.report.topics).every(t=>t.label!=='Domínio demonstrado'),'Um acerto isolado não prova domínio');
assert(topicRecommendations(enem,a.report,bank).some(x=>x.priority==='coverage'),'Planos devem contemplar conteúdo não avaliado');
assert(isGoalEvaluated(enem,[a]));
const availability={0:120,1:120,2:120,3:120,4:120,5:120,6:120};
t=buildAdaptiveSchedule({goals:[enem,contest],assessments:[a],availability,bank,days:14});
assert(t.length>=7);assert(t.every(x=>x.goalId==='a'),'Outra prova não deve receber plano sem diagnóstico');
assert(verifyPlan(t,availability).valid);assert(Object.values(verifyPlan(t,availability).totals).every(v=>v<=120));
const bq=sampleDiagnostic(bank,{...contest,provisional:true},10);const ba={id:'d2',goalId:'b',kind:'initial',status:'completed',ids:bq.map(x=>x.id),answers:{},completedAt:Date.now(),startedAt:Date.now()};ba.report=analyzeAnswers(contest,ba,bank);
const more=buildAdaptiveSchedule({goals:[enem,{...contest,provisional:true}],assessments:[a,ba],availability,bank,existing:t,days:14});
assert(verifyPlan([...t,...more],availability).valid);
assert(Object.values(verifyPlan([...t,...more],availability).totals).every(v=>v<=120));
const follow=sampleDiagnostic(bank,enem,10,a.ids);assert(follow.every(x=>!a.ids.includes(x.id)));
console.log('PASS V9: diagnóstico 20/10, segurança de prova, cobertura não avaliada, zero plano prematuro, calendário <=120 minutos, multi-provas, reteste inédito');
